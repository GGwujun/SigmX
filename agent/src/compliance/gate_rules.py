# 阶段产物（stages/*.json 的自由文本）gate 用的子串子集：免责声明会提到「目标价、止损位」，
# 机构评级分布也会出现「买入评级 31 篇」等事实——阶段侧这三个词不作裸子串拦截，
# 动作建议改由语义正则判断（report 侧仍用全量表）。
MENTIONABLE_IN_STAGE: list[str] = ["目标价", "止损", "止盈"]


def gate_stage_patterns() -> list[str]:
    """阶段产物 gate 的收窄子串表（去掉 mentionable 三词，正则表不变）。"""
    return [p for p in PATTERNS if p not in MENTIONABLE_IN_STAGE]


